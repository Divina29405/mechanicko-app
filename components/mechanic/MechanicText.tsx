export function translateMechanicValue(
  value: string,
  language: 'en' | 'fil',
) {
  if (language === 'en') return value;
  const exact = translations[value];
  if (exact) return exact;
  const uppercaseTranslation = translations[value.toLowerCase()];
  if (value === value.toUpperCase() && uppercaseTranslation) {
    return uppercaseTranslation.toUpperCase();
  }

  const radiusMatch = value.match(/^Show service requests within (\d+) km$/);
  if (radiusMatch) return `Ipakita ang service request sa loob ng ${radiusMatch[1]} km`;

  const motoristRadiusMatch = value.match(/^Show mechanics within (\d+) km$/);
  if (motoristRadiusMatch) {
    return `Ipakita ang mga mekaniko sa loob ng ${motoristRadiusMatch[1]} km`;
  }

  const progressStepMatch = value.match(/^STEP (\d+) OF 4$/);
  if (progressStepMatch) return `YUGTO ${progressStepMatch[1]} SA 4`;

  const arrivalMatch = value.match(/^~(\d+) mins arrival$/);
  if (arrivalMatch) return `Darating sa humigit-kumulang ${arrivalMatch[1]} minuto`;

  const distanceFeeMatch = value.match(/^Distance fee \((.+)\)$/);
  if (distanceFeeMatch) return `Bayad sa distansya (${distanceFeeMatch[1]})`;

  const plateMatch = value.match(/^PLATE: (.+)$/);
  if (plateMatch) return `PLAKA: ${plateMatch[1]}`;

  const servicesCountMatch = value.match(/^· (\d+) services$/);
  if (servicesCountMatch) return `· ${servicesCountMatch[1]} serbisyo`;

  const radiusSettingMatch = value.match(/^Set mechanic search radius to (\d+) kilometers$/);
  if (radiusSettingMatch) {
    return `Itakda ang saklaw ng paghahanap ng mekaniko sa ${radiusSettingMatch[1]} kilometro`;
  }

  const unreadMatch = value.match(/^Open notifications, (\d+) unread$/);
  if (unreadMatch) return `Buksan ang mga notification, ${unreadMatch[1]} hindi pa nababasa`;

  return value;
}

function translateChildren(children: ReactNode): ReactNode {
  return React.Children.map(children, (child) =>
    typeof child === 'string' ? translateMechanicValue(child, 'fil') : child,
  );
}

export function MechanicText(props: React.ComponentProps<typeof NativeText>) {
  const { language } = useAppTheme();
  const shouldTranslate = language === 'fil';
  const children =
    shouldTranslate
      ? translateChildren(props.children)
      : props.children;
  const accessibilityLabel =
    shouldTranslate && props.accessibilityLabel
      ? translateMechanicValue(props.accessibilityLabel, language)
      : props.accessibilityLabel;
  const accessibilityHint =
    shouldTranslate && props.accessibilityHint
      ? translateMechanicValue(props.accessibilityHint, language)
      : props.accessibilityHint;

  return (
    <NativeText
      {...props}
      accessibilityLabel={accessibilityLabel}
      accessibilityHint={accessibilityHint}
    >
      {children}
    </NativeText>
  );
}
